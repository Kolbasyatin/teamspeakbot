//Чат Telegram — единственный вид подписчика в системе. Объявлен здесь, а не в persistence,
//по тому же правилу, что и StoredServer в monitoring/MonitoredServer.ts: форму данных задаёт
//та часть, которой они принадлежат, а хранилище её только читает и пишет.

//Ровно те значения, которые присылает Bot API в поле chat.type.
export type TelegramChatType = "private" | "group" | "supergroup" | "channel";

//То, что мы храним про чат. Ничего сверх этого: адресация делается по chatId,
//остальное нужно человеку, который смотрит, кто подписан.
export interface TelegramChat {
    //Может быть отрицательным: у групп и каналов id вида -1001234567890.
    //number, а не bigint, осознанно: Telegram гарантирует, что id помещается в 52 бита,
    //то есть в безопасный диапазон JS. В базе колонка знаковая — см. миграцию 005.
    chatId: number;
    type: TelegramChatType;
    //У лички названия нет — там имя пользователя, и в таблицу оно не едет.
    title: string | undefined;
}
