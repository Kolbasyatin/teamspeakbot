//Экранирование для parse_mode: "HTML". Имена серверов приходят из БД и могут содержать что угодно.
//Незакрытый «<» в них — это не кривая вёрстка, а отказ Telegram разобрать сообщение целиком:
//sendMessage вернёт ошибку, и уведомление не дойдёт. В HTML достаточно трёх символов —
//в MarkdownV2 пришлось бы экранировать почти всю пунктуацию, включая точки и дефисы.
export function escapeHtml(text: string): string {
    return text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}
