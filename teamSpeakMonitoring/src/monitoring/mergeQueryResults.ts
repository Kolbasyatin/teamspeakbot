import type {ServerQueryResult} from "./ServerQuery.js";

//Слияние ответов нескольких источников одного сервера в один результат.
//Чистая функция, потому что ни сети, ни БД для этого не нужно — нужны фикстуры.
//
//Правило одно: поле за полем, побеждает первое определённое значение. Никакой настройки
//"источник X отвечает за поле Y" здесь нет: что источник умеет отдать — свойство его типа,
//а под каким именем это лежит в чужом ответе — дело карты полей в конфиге источника.
//Слиянию достаётся уже разобранный доменный результат, и настраивается только приоритет,
//то есть порядок аргументов.
//
//Списка полей нет намеренно. Здесь нечего искать: ключи приезжают вместе с данными, поэтому
//забыть поле невозможно в принципе. Список (бывший MERGEABLE_FIELDS) защищал ровно от той
//проблемы, которую сам и создавал — его можно было не пополнить.

//results — в порядке убывания приоритета. undefined на месте источника означает "не ответил":
//он просто не участвует, а не обнуляет поле, уже заполненное источником повыше.
export function mergeQueryResults(
    results: readonly (ServerQueryResult | undefined)[],
): ServerQueryResult {
    //Record<string, unknown> внутри, потому что присваивание по вычисленному ключу иначе
    //не типизируется. Наружу уходит ServerQueryResult: ключи взяты из таких же результатов,
    //посторонним появиться неоткуда.
    const merged: Record<string, unknown> = {};

    for (const result of results) {
        if (!result) {
            continue;
        }

        for (const [field, value] of Object.entries(result)) {
            //Проверка на undefined, а не на truthiness: players: 0 — это пустой онлайн-сервер,
            //то есть значение, а не отсутствие данных.
            if (value !== undefined && merged[field] === undefined) {
                merged[field] = value;
            }
        }
    }

    return merged as ServerQueryResult;
}
