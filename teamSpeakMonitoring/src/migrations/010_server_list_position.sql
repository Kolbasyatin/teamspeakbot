-- Позиция сервера в списках бота (итерация 15): «эти серверы — в самом верху».
--
-- NULL — позиции нет, сервер идёт в общем порядке по имени. Число — место среди закреплённых:
-- меньше — выше. Закреплённые всегда идут раньше незакреплённых.
--
-- Число, а не флаг «закреплён»: закреплённых бывает несколько, и между ними тоже нужен порядок.
-- Уникальности нет намеренно: два сервера с одной позицией не ошибка, их порядок добьёт имя, —
-- а UNIQUE заставлял бы переставлять соседей при каждой правке.
--
-- Это порядок ПОКАЗА в боте, к опросу отношения не имеет: в конфиг опроса позиция не попадает,
-- иначе её смена пересоздавала бы probe и сбрасывала состояние сервера.

ALTER TABLE monitored_servers
    ADD COLUMN IF NOT EXISTS list_position int null;
