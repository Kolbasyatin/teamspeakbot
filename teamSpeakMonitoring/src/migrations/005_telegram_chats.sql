-- Чат Telegram как подписчик. До этой миграции понятия «кому мы пишем» в системе не было вовсе:
-- адресат один и лежал в переменной окружения TELEGRAM_CHANNEL_ID.
--
-- Подписчик — ЧАТ, а не пользователь. Bot API адресует сообщения по chat_id: для лички он равен
-- user_id, для группы и канала это отдельное отрицательное число. Возьми ключом user_id — и подписка
-- группы («уведомляйте наш клан в общем чате») либо не выражается вовсе, либо требует второй таблицы
-- и второго пути доставки. С chat_id личка, группа и нынешний канал из env — одна и та же сущность
-- с разным значением поля type.
--
-- chat_id ЗНАКОВЫЙ bigint, и это не оплошность: id групп и каналов отрицательные
-- (вида -1001234567890). unsigned здесь сломал бы ровно тот случай, ради которого таблица заводится.
-- auto_increment нет по той же причине: ключ выдаёт Telegram, а не мы.
--
-- title заполняется для групп и каналов; у лички названия нет, там имя пользователя. Нужен он
-- только человеку — понять, кто это, глядя в таблицу; логика на него не завязана.
-- Пишется при регистрации чата, потому что позже взять его будет неоткуда: название приезжает
-- вместе с апдейтом, и добавленная потом колонка осталась бы пустой до следующего сообщения.
--
-- Колонки blocked_at здесь намеренно НЕТ, хотя она понадобится: её пишет только отправка сообщений
-- (403 «bot was blocked by the user»), а отправки адресатам ещё не существует. Заведём вместе
-- с тем, кто в неё пишет, — по тому же правилу, по которому в итерации 3 отказались от поля queue
-- «на будущее». ALTER ADD COLUMN на nullable-колонку ничего не стоит.

CREATE TABLE IF NOT EXISTS telegram_chats
(
    chat_id    bigint                                          not null
        primary key,
    type       enum ('private','group','supergroup','channel')  not null,
    title      varchar(255)                                     null,
    created_at timestamp default current_timestamp()            not null,
    updated_at timestamp default current_timestamp()            not null on update current_timestamp()
)
