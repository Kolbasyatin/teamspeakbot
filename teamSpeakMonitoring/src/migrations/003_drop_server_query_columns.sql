-- Убирает из monitored_servers колонки опроса: после 002 источники живут в server_query_sources,
-- и оставлять их здесь означало бы держать два источника правды с неизбежным расхождением.
--
-- Отдельным файлом от 002 по той же причине, по которой миграции держим мелкими: DDL в MariaDB
-- не транзакционный. Перенос данных к этому моменту уже применён и записан в schema_migrations,
-- поэтому упавший ALTER повторится сам по себе и ничего не потеряет.
--
-- IF EXISTS — чтобы повторный запуск после частичного отказа был безопасен.

ALTER TABLE monitored_servers
    DROP COLUMN IF EXISTS query_type,
    DROP COLUMN IF EXISTS query_config;
