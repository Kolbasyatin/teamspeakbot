-- Карта полей для rest-источников: где в ответе искать каждое доменное поле.
--
-- Зачем: до этой миграции RestQuerier читал из JSON поля с именами players и maxPlayers, то есть
-- предполагал, что чужой эндпоинт называет их ровно так же, как домен. Верно это только для API,
-- написанного под этот проект. У A2S такой карты нет и не будет — там форма ответа фиксирована
-- протоколом, настраивать нечего.
--
-- Существующим источникам проставляется ровно то поведение, которое у них было: имена совпадают.
-- Явно, а не значением по умолчанию в коде: умолчание вернуло бы то же неверное предположение,
-- только неявным, и разбираться, откуда взялись имена, пришлось бы в исходниках.
--
-- Идемпотентно: условие отсекает источники, у которых карта уже есть. Повторный запуск после
-- отказа, не записавшего версию, ничего не перезапишет — в том числе карту, правленную руками.

UPDATE server_query_sources
SET query_config = JSON_SET(
        query_config,
        '$.fields',
        JSON_OBJECT('players', 'players', 'maxPlayers', 'maxPlayers')
                   )
WHERE query_type = 'rest'
  AND JSON_EXTRACT(query_config, '$.fields') IS NULL;
