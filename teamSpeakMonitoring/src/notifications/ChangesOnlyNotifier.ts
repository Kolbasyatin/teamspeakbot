import type {Notifier, NotificationEventOf, NotificationEventType} from "./events.js";

//Обёртка над нотифаером: доставляет событие только если по этому предмету ещё не доставлено
//такое же состояние. Помнит **последнюю успешную** доставку — упавшая не запоминается и повторится.
//
//Зачем: канал Telegram — это журнал, а не табло. Периодическая синхронизация состояния присылает
//статус каждого сервера каждую минуту, и без этой обёртки в канал ушло бы 1440 сообщений
//«is online» в сутки. С ней тик молчит, пока состояние совпадает с доставленным, и оживает ровно
//в двух случаях: состояние действительно изменилось, либо прошлая отправка не удалась.
//
//Правила задаются при сборке двумя функциями, и они про РАЗНОЕ:
//
//  subjectOf  — ЯЧЕЙКА памяти, «про что сообщение». Одна ячейка на предмет, новое значение
//               её перезаписывает. Для Telegram предмет — сервер (падение одного не глушит
//               сообщение про другой), для описания канала — константа: табло одно на всё.
//  dedupKeyOf — СОДЕРЖИМОЕ ячейки, «что именно мы сказали». Сравнивается именно оно.
//               Наружу не уходит: получателю отдаётся событие целиком.
//
//Требование к паре, и проверить его может только тот, кто собирает: **два события с одинаковой
//парой (subject, dedupKey) обязаны быть неразличимы для получателя, а различимые обязаны эту пару
//различать**. Ключ грубее нужного — сообщения теряются; тоньше — обёртка становится дорогим no-op
//(так вышло бы, попади в ключ описания канала отметка времени: она меняется каждую секунду).
//Отсюда и ключ табло — весь текст описания целиком: любое поле, попавшее человеку на глаза,
//обязано попасть в ключ, и «весь текст» — единственный способ этого не забыть.
//
//Классическая ошибка — сложить «про что» и «что именно» в один subject, например id + тип события.
//Тогда ячейки не перезаписываются, а копятся, и повтор становится невозможен:
//    online  → ячейки "1:serverOnline" нет  → отправили, создали
//    offline → ячейки "1:serverOffline" нет → отправили, создали
//    online  → ячейка "1:serverOnline" ЕСТЬ → молчим, и так навсегда
//Закреплено тестом «оба события обслуживает один экземпляр обёртки, иначе память разъезжается».
//
//Память живёт в процессе: после рестарта первый тик отправит статусы заново. Это не регресс —
//сейчас то же самое делает переход unknown → online на первом опросе (долг, п. 14).
export class ChangesOnlyNotifier<TType extends NotificationEventType> implements Notifier<TType> {
    private readonly delivered = new Map<string, string>();

    constructor(
        private readonly inner: Notifier<TType>,
        private readonly subjectOf: (event: NotificationEventOf<TType>) => string,
        private readonly dedupKeyOf: (event: NotificationEventOf<TType>) => string,
    ) {
    }

    public async notify(event: NotificationEventOf<TType>): Promise<void> {
        const subject = this.subjectOf(event);
        const dedupKey = this.dedupKeyOf(event);

        if (this.delivered.get(subject) === dedupKey) {
            return;
        }

        //Запоминаем ДО отправки, а при отказе откатываем. Иначе два одновременных вызова с одним
        //ключом (тик и реальный переход статуса приходят независимо, через void) оба прошли бы
        //проверку до того, как первый успел записаться, — и в канал ушло бы два одинаковых сообщения.
        this.delivered.set(subject, dedupKey);

        try {
            await this.inner.notify(event);
        } catch (error) {
            //Откатываем только своё: если за время отправки по этому же предмету доставили другое
            //состояние, затирать его нельзя.
            if (this.delivered.get(subject) === dedupKey) {
                this.delivered.delete(subject);
            }

            throw error;
        }
    }
}
